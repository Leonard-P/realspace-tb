"""
Command line:  python -m realspace_tb.workflow <command> CONFIG [options]

    count  CONFIG                      number of runs in the sweep
    list   CONFIG                      index, run id, swept parameters, done or not
    run    CONFIG [--index I | --all]  run one (default: $SLURM_ARRAY_TASK_ID) or all runs
    slurm  CONFIG --account A [...]    write a Slurm array script for the sweep (and submit it)
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

from .config import expand, load_config
from .runner import is_done, run_dir, run_simulation

SLURM_TEMPLATE = """#!/bin/bash
# generated by: python -m realspace_tb.workflow slurm {config}
#SBATCH -J {job_name}
#SBATCH -A {account}
#SBATCH -p {partition}
#SBATCH -N 1
#SBATCH -n 1
#SBATCH --cpus-per-task={cpus}
#SBATCH --mem={mem}
#SBATCH -t {time}
#SBATCH --array=0-{last}{throttle}
#SBATCH -o {log_dir}/%x_%A_%a.out
{qos_line}
set -eo pipefail
source "{env_file}"
srun "$PYTHON" -m realspace_tb.workflow run "{config}" --index "$SLURM_ARRAY_TASK_ID"
"""


def _runs(path: str) -> list[dict]:
    return expand(load_config(path))


def cmd_count(args) -> None:
    print(len(_runs(args.config)))


def cmd_list(args) -> None:
    for r in _runs(args.config):
        status = "done" if is_done(r) else "todo"
        swept = ", ".join(f"{k}={v}" for k, v in r["_swept"].items()) or "-"
        print(f"{r['_index']:4d}  {r['_run_id']}  {status}  {swept}")


def cmd_run(args) -> None:
    runs = _runs(args.config)
    if args.all:
        selected = runs
    else:
        index = args.index if args.index is not None else os.environ.get("SLURM_ARRAY_TASK_ID")
        if index is None:
            sys.exit("give --index I or --all (or run inside a Slurm array task)")
        index = int(index)
        if not 0 <= index < len(runs):
            sys.exit(f"index {index} out of range: the sweep has {len(runs)} runs (0..{len(runs) - 1})")
        selected = [runs[index]]
    for r in selected:
        if args.n_workers is not None:
            r["method"]["n_workers"] = args.n_workers
        run_simulation(r, force=args.force, progress=args.progress)


def cmd_slurm(args) -> None:
    config = str(Path(args.config).resolve())
    runs = _runs(config)
    todo = [r["_index"] for r in runs if not is_done(r)]
    name = runs[0]["name"]
    env_file = str(Path(args.env).resolve())
    log_dir = str(Path(args.log_dir).resolve())
    script = SLURM_TEMPLATE.format(
        config=config, job_name=args.job_name or name, account=args.account, partition=args.partition,
        cpus=args.cpus, mem=args.mem, time=args.time, last=len(runs) - 1,
        throttle=f"%{args.max_parallel}" if args.max_parallel else "",
        log_dir=log_dir, env_file=env_file,
        qos_line=f"#SBATCH -q {args.qos}\n" if args.qos else "",
    )
    out = Path(args.script or f"{name}.slurm")
    out.write_text(script)
    Path(log_dir).mkdir(parents=True, exist_ok=True)
    print(f"wrote {out}: {len(runs)} runs ({len(todo)} not done yet), {args.cpus} cores each")
    if args.submit:
        array = ",".join(map(str, todo)) if len(todo) < len(runs) else f"0-{len(runs) - 1}"
        if not todo:
            print("nothing to do: all runs are finished")
            return
        throttle = f"%{args.max_parallel}" if args.max_parallel else ""
        cmd = ["sbatch", f"--array={array}{throttle}", str(out)]
        print(" ".join(cmd))
        subprocess.run(cmd, check=True)
    else:
        print(f"submit with:  sbatch {out}")


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(prog="python -m realspace_tb.workflow", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)

    for name, func in (("count", cmd_count), ("list", cmd_list)):
        sp = sub.add_parser(name)
        sp.add_argument("config")
        sp.set_defaults(func=func)

    sp = sub.add_parser("run")
    sp.add_argument("config")
    group = sp.add_mutually_exclusive_group()
    group.add_argument("--index", type=int)
    group.add_argument("--all", action="store_true")
    sp.add_argument("--n-workers", type=int, default=None, help="override method.n_workers")
    sp.add_argument("--force", action="store_true", help="recompute even if results exist")
    sp.add_argument("--progress", action="store_true")
    sp.set_defaults(func=cmd_run)

    sp = sub.add_parser("slurm")
    sp.add_argument("config")
    sp.add_argument("--account", required=True)
    sp.add_argument("--partition", default="normal")
    sp.add_argument("--qos", default=None)
    sp.add_argument("--cpus", type=int, default=16)
    sp.add_argument("--mem", default="16G")
    sp.add_argument("--time", default="04:00:00")
    sp.add_argument("--max-parallel", type=int, default=None, help="at most this many tasks at once")
    sp.add_argument("--env", default="cluster_env.sh", help="environment file sourced by each task")
    sp.add_argument("--log-dir", default="logs")
    sp.add_argument("--job-name", default=None)
    sp.add_argument("--script", default=None, help="output file (default: <name>.slurm)")
    sp.add_argument("--submit", action="store_true", help="submit the runs that are not done yet")
    sp.set_defaults(func=cmd_slurm)

    args = p.parse_args(argv)
    args.func(args)


if __name__ == "__main__":   # required: parallel k-chunk workers re-import the main module
    main()
